from io import BytesIO
from reportlab.lib.pagesizes import A4
from reportlab.lib.utils import simpleSplit
from reportlab.pdfgen import canvas

FOOTER = "Generated by Nyay Saathi. General information, not legal advice."


def _latin(s: str) -> str:
    return s.encode("latin-1", "replace").decode("latin-1")     # built-in PDF fonts cannot draw Devanagari


def text_to_pdf(text: str, title: str = "Draft") -> bytes:
    buf = BytesIO()
    c = canvas.Canvas(buf, pagesize=A4)
    w, h = A4
    margin = 50
    c.setTitle(_latin(title))

    def page_header():
        c.setFont("Helvetica-Bold", 12)
        c.drawString(margin, h - margin, _latin(title))
        c.setFont("Helvetica", 10)
        return h - margin - 26

    def footer():
        c.setFont("Helvetica-Oblique", 8)
        c.drawString(margin, 30, FOOTER)
        c.setFont("Helvetica", 10)

    y = page_header()
    for para in text.split("\n"):
        for line in simpleSplit(_latin(para) or " ", "Helvetica", 10, w - 2 * margin):
            if y < margin + 20:
                footer(); c.showPage(); y = page_header()
            c.drawString(margin, y, line)
            y -= 14
    footer()
    c.save()
    return buf.getvalue()
